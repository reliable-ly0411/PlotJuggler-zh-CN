"""Generate exact pinned-UI presentation keys, without changing plugin payloads."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
def generated():
    data = json.loads((ROOT / 'packaging/localization/bundled-ui-translations.json').read_text(encoding='utf-8'))
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    lines = ['// Generated by packaging/localization/generate_bundled_ui_translations.py.',
             '// SPDX-License-Identifier: MPL-2.0', 'constexpr const char* kBundledUiHashes[] = {']
    lines += ['    ' + quote(ui['sha256']) + ',' for ui in data['uis']]
    lines += ['};', 'constexpr DisplayEntry kDisplayEntries[] = {']
    for row in data['exact']:
        args = [quote(row[key]) for key in ('scope', 'widget', 'property')]
        args.append('QT_TRANSLATE_NOOP("PJ::BundledPlugins", ' + quote(row['source']) + ')')
        lines.append('    {' + ', '.join(args) + '},')
    lines += ['};', 'constexpr TemplateEntry kTemplateEntries[] = {']
    for row in data['templates']:
        args = [quote(row[key]) for key in ('scope', 'widget', 'property', 'pattern')]
        args.append('QT_TRANSLATE_NOOP("PJ::BundledPlugins", ' + quote(row['source']) + ')')
        lines.append('    {' + ', '.join(args) + '},')
    return '\n'.join(lines + ['};', ''])
if __name__ == '__main__':
    (ROOT / 'pj_dialog_host/src/bundled_translation_entries.hpp').write_text(generated(), encoding='utf-8')
